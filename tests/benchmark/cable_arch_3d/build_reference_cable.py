#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从冻结的 ANSYS CSV 生成 cable_arch_3d 黄金参考值。

参考值**全部来自真实 ANSYS 18.0 批处理导出的 CSV**，不手工填数。
每个检查项都记录 ``source = 文件名:行键:列号``，``--check`` 可随时
验证 JSON 与 CSV 是否脱节。

用法：
    python build_reference_cable.py            # 生成 reference/*.json
    python build_reference_cable.py --check    # 只校验一致性，不写文件
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES = HERE / "cases"
REF = HERE / "reference"

CSV_PATTERN = {
    "disp": "{stem}_ansys_disp.csv",
    "reac": "{stem}_ansys_reac.csv",
    "beam": "{stem}_ansys_beam.csv",
    "link": "{stem}_ansys_link.csv",
}
CSV_LABEL = {
    "disp": "UX/UY/UZ/ROTX/ROTY/ROTZ",
    "reac": "FX/FY/FZ/MX/MY/MZ",
    "beam": "BEAM4 i-end N/Vy/Vz/T/My/Mz",
    "link": "LINK180 axial force SMISC 1",
}

CASES_SPEC = [
    {
        "id": "cb3d03_cable_stayed",
        "title": "CB3D03 single-pylon cable-stayed bridge 3D (BEAM + CABLE)",
        "description": "L=60 m, 12 BEAM deck elements, rigid tower anchor at z=18 m, "
                       "6 CABLE stays, nodalized q=20 kN/m",
        "nnode": 14, "nbeam": 12, "nlink": 6,
        "beam_ids": list(range(1, 13)),
        "link_ids": list(range(13, 19)),
        "support_nodes": [1, 13, 14],
    },
    {
        "id": "cb3d04_arch_bridge",
        "title": "CB3D04 parabolic arch bridge 3D (BEAM rib/deck + TRUSS hangers)",
        "description": "L=60 m, rise=12 m, 12 BEAM deck + 12 BEAM arch-rib segments "
                       "+ 11 vertical TRUSS hangers, nodalized q=20 kN/m",
        "nnode": 24, "nbeam": 24, "nlink": 11,
        "beam_ids": list(range(1, 25)),
        "link_ids": list(range(25, 36)),
        "support_nodes": [1, 13],
    },
]

DISP_NAMES = ("UX", "UY", "UZ", "ROTX", "ROTY", "ROTZ")
BEAM_NAMES = ("N", "Vy", "Vz", "T", "My", "Mz")


def read_csv_table(path: Path) -> dict[int, list[float]]:
    rows: dict[int, list[float]] = {}
    for raw in path.read_text(encoding="ascii", errors="replace").splitlines():
        toks = raw.replace(",", " ").split()
        if len(toks) < 2:
            continue
        try:
            vals = [float(t) for t in toks]
        except ValueError:
            continue
        rows[int(round(vals[0]))] = vals[1:]
    return rows


def build_one(spec: dict) -> dict:
    stem = spec["id"]
    tables = {}
    for kind, pat in CSV_PATTERN.items():
        p = CASES / pat.format(stem=stem)
        if not p.exists():
            raise FileNotFoundError("缺少冻结 ANSYS CSV: %s" % p)
        tables[kind] = read_csv_table(p)

    checks: list[dict] = []

    def mk(name, kind, key, col, ref, *, abs_=False, atol=1e-6):
        checks.append({
            "name": name, "kind": kind, "key": key, "col": col,
            "ref": ref, "rtol": 1e-3, "atol": atol,
            "abs": abs_,
            "source": "%s:%s:col%d" % (CSV_PATTERN[kind].format(stem=stem), key, col + 1),
        })

    # 1) 全量节点位移 6 DOF（FEM-Eigen .report.txt 与 ANSYS 逐位对应）
    for nd in range(1, spec["nnode"] + 1):
        row = tables["disp"].get(nd)
        if row is None or len(row) < 6:
            raise ValueError("%s disp 缺节点 %d" % (stem, nd))
        for c, nm in enumerate(DISP_NAMES):
            mk("disp_n%d_%s" % (nd, nm), "disp", nd, c, row[c], atol=1e-9)

    # 2) 全量 BEAM i 端 6 分量（幅值：两套内核端力符号约定不同）
    for eid in spec["beam_ids"]:
        row = tables["beam"].get(eid)
        if row is None or len(row) < 6:
            raise ValueError("%s beam 缺单元 %d" % (stem, eid))
        for c, nm in enumerate(BEAM_NAMES):
            mk("beam_e%d_%s" % (eid, nm), "beam", eid, c, abs(row[c]), abs_=True)

    # 3) 全量轴向杆轴力（LINK180 SMISC 1）
    for eid in spec["link_ids"]:
        row = tables["link"].get(eid)
        if row is None or not row:
            raise ValueError("%s link 缺单元 %d" % (stem, eid))
        mk("link_e%d_N" % eid, "link", eid, 0, abs(row[0]), abs_=True)

    # 4) 支座竖向反力（仅 live-ansys 模式与 ANSYS 重跑结果比对）
    reactions = []
    for nd in spec["support_nodes"]:
        row = tables["reac"].get(nd, [0.0] * 6)
        reactions.append({"node": nd, "fz": row[2]})
    fz_sum = sum(r["fz"] for r in reactions)

    return {
        "id": stem,
        "title": spec["title"],
        "description": spec["description"],
        "dat": stem + ".dat",
        "apdl": stem + ".inp",
        "exe": "example_3d_report.exe",
        "reference_source": (
            "ANSYS 18.0 (BEAM4 + LINK180) batch results frozen in "
            "cases/%s_ansys_{disp,reac,beam,link}.csv; generated by "
            "BridgeStudio/ansys_bridge_cable.py from the same ModelSpec3D" % stem
        ),
        "csv": {k: v.format(stem=stem) for k, v in CSV_PATTERN.items()},
        "csv_label": CSV_LABEL,
        "expected_rows": {
            "disp": spec["nnode"], "reac": spec["nnode"],
            "beam": spec["nbeam"], "link": spec["nlink"],
        },
        "support_nodes": spec["support_nodes"],
        "support_fz_sum": fz_sum,
        "checks": checks,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="只校验已生成 JSON 与冻结 CSV 是否一致")
    a = ap.parse_args()
    REF.mkdir(parents=True, exist_ok=True)
    bad = 0
    for spec in CASES_SPEC:
        data = build_one(spec)
        out = REF / (spec["id"] + "_ansys.json")
        if a.check:
            if not out.exists():
                print("[FAIL] missing %s" % out.name)
                bad += 1
                continue
            old = json.loads(out.read_text(encoding="utf-8"))
            if old == data:
                print("[PASS] %s  %d checks match frozen CSV" %
                      (out.name, len(data["checks"])))
            else:
                print("[FAIL] %s out of sync with frozen CSV" % out.name)
                bad += 1
        else:
            out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                           encoding="utf-8")
            print("[WRITE] %s  %d checks" % (out.name, len(data["checks"])))
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
